"""Generate/check the repository's module inventory, without build artifacts."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
EXCLUDED = {"bin", "obj", "__pycache__", ".git", ".tools", "artifacts", "TestResults"}


def files(folder):
    return sorted(p for p in folder.rglob("*") if p.is_file() and not EXCLUDED.intersection(p.relative_to(ROOT).parts))


def inventory():
    lines = ["# Module inventory and file counts", "", "Generated by `python scripts/module-map.py`; `--check` detects stale inventory.",
             "Counts exclude build output, SDKs and local evidence. Submodule rows are subsets of project totals, not additional files.", "",
             "| Module | C# .cs | UI .axaml | Markdown | All files |", "| --- | ---: | ---: | ---: | ---: |"]

    def row(folder):
        entries = files(folder)
        if not entries:
            return
        relative = folder.relative_to(ROOT).as_posix()
        readme = folder / "README.md"
        target = "../" + relative + ("/README.md" if readme.exists() else "/")
        counts = [sum(p.suffix == suffix for p in entries) for suffix in (".cs", ".axaml", ".md")]
        lines.append(f"| [{relative}]({target}) | {' | '.join(map(str, counts))} | {len(entries)} |")

    for project in sorted((ROOT / "src").iterdir()):
        if not project.is_dir():
            continue
        row(project)
        for module in sorted(project.iterdir()):
            if module.is_dir() and module.name not in EXCLUDED | {"Licenses"}:
                row(module)
                if module.name == "Research":
                    for submodule in sorted(module.iterdir()):
                        if submodule.is_dir():
                            row(submodule)
    for name in ("tests", "benchmarks", "scripts", "docs", "research", ".github"):
        row(ROOT / name)
    lines.extend(["", "Peripheral modules reuse .NET/BCL and mature SDKs; adaptation boundaries are in adjacent README/PROVENANCE files.",
                  "Kernel paper mechanisms and project additions are documented in Context, Memory, Research and RepositoryMemory READMEs.",
                  "This generated file counts toward docs; upstream notices count toward their owning project.", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "docs/module-map.md"
    if not args.check:
        destination.touch(exist_ok=True)
    content = inventory()
    if args.check:
        if not destination.exists() or destination.read_text(encoding="utf-8") != content:
            raise SystemExit("Module map is stale: run python scripts/module-map.py")
        print("Module map is current.")
    else:
        destination.write_text(content, encoding="utf-8")
        print("Wrote docs/module-map.md")
